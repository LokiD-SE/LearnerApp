"""Validate one uploaded file the way the OWASP File Upload Cheat Sheet asks - before anything is stored.

SandPay lets a merchant attach dispute evidence: a PNG, a JPEG or a PDF, at most 1 MiB. The cheat sheet's
principles that this function applies:

- "List allowed extensions" - and validate after decoding the name, rejecting the known bypasses: double
  extensions, null bytes, case changes, trailing dots or spaces, and ``:`` (NTFS alternate data streams).
- "Validate the file type, don't trust the Content-Type header as it can be spoofed" - here the declared type is
  ignored and the file's first bytes (its signature) must match its extension. The cheat sheet adds that a
  signature check "should not be used on its own", so this is one layer, not the whole defence.
- "Change the filename to something generated by the application" - the stored name is a random id plus the
  validated extension; the client's name is never used to build a path.
- "Set a file size limit".

``download_headers`` shows what the file is served with so that an uploaded file cannot run as a page: the
type the server decided, ``nosniff``, and ``attachment`` (MDN: ``attachment`` indicates the content "should be
downloaded"; ``X-Content-Type-Options: nosniff`` makes browsers use the supplied Content-Type "as-is").
"""

from __future__ import annotations

import secrets
from dataclasses import dataclass
from typing import Callable

# extension -> (content type the server will use, the bytes a real file of that type starts with)
ALLOWED = {
    ".png": ("image/png", b"\x89PNG\r\n\x1a\n"),
    ".jpg": ("image/jpeg", b"\xff\xd8\xff"),
    ".pdf": ("application/pdf", b"%PDF-"),
}
MAX_BYTES = 1_048_576
MAX_NAME = 100


class UploadRejected(ValueError):
    """The upload breaks a rule; the message says which one."""


@dataclass(frozen=True)
class StoredUpload:
    stored_name: str  # "<random id><extension>" - never derived from the client's name
    content_type: str  # decided by the server from the extension and signature
    size: int


def validate_upload(
    filename: str,
    declared_type: str,
    data: bytes,
    new_id: Callable[[], str] = lambda: secrets.token_hex(16),
) -> StoredUpload:
    """Returns a StoredUpload, or raises UploadRejected. ``declared_type`` is the client's Content-Type: ignore it.

    Rules, in this order:
    1. size: ``data`` must not be empty and must be at most ``MAX_BYTES``;
    2. name: at most ``MAX_NAME`` characters; no NUL, ``/``, ``\\`` or ``:``; must not end with a dot or a space;
       must have a stem and an extension (a dot that is not the first character);
    3. extension: the text after the LAST dot, lower-cased, must be a key of ``ALLOWED`` (so ``.PNG`` passes,
       ``shell.png.php`` and ``evil.phtml`` do not);
    4. signature: ``data`` must start with the bytes ``ALLOWED`` lists for that extension;
    5. build ``StoredUpload(new_id() + extension, content_type, len(data))``.

    The messages of the size, extension and signature rejections contain the words ``size``, ``extension`` and
    ``content`` so that a log line says which rule fired.
    """
    if not data or len(data) > MAX_BYTES:
        raise UploadRejected(f"size must be 1 to {MAX_BYTES} bytes")
    if len(filename) > MAX_NAME or any(ch in filename for ch in "\x00/\\:") or filename.endswith((".", " ")):
        raise UploadRejected("unacceptable file name")
    stem, dot, extension = filename.rpartition(".")
    if not dot or not stem:
        raise UploadRejected("file name needs a stem and an extension")
    extension = "." + extension.lower()
    if extension not in ALLOWED:
        raise UploadRejected(f"extension {extension!r} is not allowed")
    content_type, signature = ALLOWED[extension]
    if not data.startswith(signature):
        raise UploadRejected("content does not match the extension")
    return StoredUpload(new_id() + extension, content_type, len(data))


def download_headers(upload: StoredUpload) -> dict[str, str]:
    """Headers for serving a stored upload: ``Content-Type`` (the server's decision), ``X-Content-Type-Options:
    nosniff`` and ``Content-Disposition: attachment; filename="<stored_name>"``."""
    return {
        "Content-Type": upload.content_type,
        "X-Content-Type-Options": "nosniff",
        "Content-Disposition": f'attachment; filename="{upload.stored_name}"',
    }
